#!/usr/bin/env python3
"""Install QRL-Lab v0.3 (dispatcher mode). Run by the researcher in ~/qrl-lab, not by an agent.

  python3 tools/install_v03.py            show what would change (writes nothing)
  python3 tools/install_v03.py --apply    apply; every file it changes is first copied to .lab/backup-v03-<time>/

Safe to run twice: each step checks first and skips what is already there. It only ADDS:
  - permission entries to .claude/settings.json (merge; nothing removed or reordered)
  - one marked section at the end of CLAUDE.md and of AGENTS.md
  - docs/STATE.md from the template (only if missing), docs/journal/
  - the coordinator panel at the end of dashboard/app.py (wrapped so it can never break the dashboard)
  - ~/.codex/rules/qrl-lab.rules, ~/.config/qrl-lab/env, two systemd user units
Then it builds docs/INDEX.md and prints the few commands that need you (sudo, systemctl).
"""
import argparse
import datetime as dt
import json
import os
import shutil
import sys

ROOT = os.path.abspath(os.environ.get("QRL_LAB_DIR") or os.path.join(os.path.dirname(__file__), ".."))
HOME = os.path.expanduser("~")
MARK_CLAUDE = "<!-- qrl-v0.3 dispatcher -->"
MARK_AGENTS = "<!-- qrl-v0.3 shared memory -->"
MARK_APP = "# qrl-v0.3 coordinator panel"

CLAUDE_SECTION = f"""
{MARK_CLAUDE}
## Dispatcher mode (v0.3)
When your task text starts with `[QRL-Lab task`, you were started headless by `tools/dispatcher.py` for one task:
follow `prompts/coordinator.md` (also in your system prompt) instead of the QRL-INBOX protocol above. Your final
message is posted to the dashboard by the dispatcher. Ask Codex with `python3 tools/ask_peer.py` (logged, and it works
the same when Codex coordinates); the `codex:codex-rescue` subagent stays available in interactive sessions.
"""

AGENTS_SECTION = f"""
{MARK_AGENTS}
## Shared memory and coordination (both models)
- Every task starts from `docs/STATE.md`, the strategic handoff (at most 150 lines). Whoever coordinates updates it at
  the end of any task that changed something, so the other model can take over without reading old conversations.
- Other notes: search `docs/INDEX.md` (generated by `tools/build_md_index.py`; do not edit it, do not read it whole).
  Accepted decisions: `docs/DECISIONS.md`. One line per task: `docs/journal/`.
- Either model can be the coordinator: the researcher chooses in the dashboard, and the dispatcher hands the task to
  the other model when one reaches its usage limit. If your task text starts with `[QRL-Lab task`, you ARE the
  coordinator: follow `prompts/coordinator.md`; the other model is your co-researcher through `tools/ask_peer.py`.
- Never change `.claude/settings.json`, `~/.codex/`, `prompts/`, the systemd units or the dispatcher settings unless
  the researcher asks for that change.
"""

APP_SNIPPET = f"""

{MARK_APP} (added by tools/install_v03.py; remove this block to remove the panel)
try:
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    from coord_panel import render_coordinator_panel
    with st.sidebar:
        render_coordinator_panel()
except Exception as _qrl_panel_error:  # the panel must never break the dashboard
    st.sidebar.warning(f"Πάνελ συντονιστή: {{_qrl_panel_error}}")
"""


class Installer:
    def __init__(self, root, apply):
        self.root, self.apply = root, apply
        self.backup = os.path.join(root, ".lab", "backup-v03-" + dt.datetime.now().strftime("%Y%m%d-%H%M%S"))
        self.changes = []

    def _backup(self, path):
        if not os.path.exists(path):
            return
        rel = os.path.relpath(path, self.root) if path.startswith(self.root) else "home" + path[len(HOME):]
        dst = os.path.join(self.backup, rel)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copy2(path, dst)

    def write(self, path, text, what):
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if old == text:
            return
        self.changes.append(what)
        if self.apply:
            self._backup(path)
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8") as f:
                f.write(text)

    def append_once(self, rel, marker, section):
        p = os.path.join(self.root, rel)
        old = open(p, encoding="utf-8").read() if os.path.exists(p) else ""
        if marker in old:
            return
        self.write(p, old.rstrip("\n") + "\n" + section, f"{rel}: πρόσθεση ενότητας ({marker})")

    def merge_settings(self):
        p = os.path.join(self.root, ".claude", "settings.json")
        add = json.load(open(os.path.join(self.root, "deploy", "settings-additions.json"), encoding="utf-8"))
        cur = json.load(open(p, encoding="utf-8")) if os.path.exists(p) else {}
        perms = cur.setdefault("permissions", {})
        added = []
        for kind in ("allow", "deny"):
            lst = perms.setdefault(kind, [])
            for e in add["permissions"][kind]:
                if e not in lst:
                    lst.append(e)
                    added.append(f"{kind}: {e}")
        if added:
            self.write(p, json.dumps(cur, indent=2, ensure_ascii=False) + "\n",
                       ".claude/settings.json: +" + "; ".join(added))

    def copy_template(self, src_rel, dst_rel, only_if_missing=True):
        src, dst = os.path.join(self.root, src_rel), os.path.join(self.root, dst_rel)
        if only_if_missing and os.path.exists(dst):
            return
        self.write(dst, open(src, encoding="utf-8").read(), f"{dst_rel}: νέο αρχείο από {src_rel}")

    def home_file(self, src_rel, dst, subst=None):
        text = open(os.path.join(self.root, src_rel), encoding="utf-8").read()
        for k, v in (subst or {}).items():
            text = text.replace(k, v)
        self.write(dst, text, f"{dst.replace(HOME, '~')}")

    def env_file(self):
        path_value = os.environ.get("PATH", "/usr/bin:/bin")
        text = (f"# Written by tools/install_v03.py: the PATH where `claude` and `codex` were found.\n"
                f"PATH={path_value}\nQRL_LAB_DIR={self.root}\nPYTHONUNBUFFERED=1\n")
        self.write(os.path.join(HOME, ".config", "qrl-lab", "env"), text, "~/.config/qrl-lab/env (PATH, QRL_LAB_DIR)")

    def run(self):
        missing = [b for b in ("claude", "codex") if not shutil.which(b)]
        if missing:
            print(f"ΠΡΟΣΟΧΗ: δεν βρέθηκαν στο PATH: {', '.join(missing)}. Τρέξε πρώτα: source ~/.nvm/nvm.sh")
        self.merge_settings()
        self.append_once("CLAUDE.md", MARK_CLAUDE, CLAUDE_SECTION)
        self.append_once("AGENTS.md", MARK_AGENTS, AGENTS_SECTION)
        self.copy_template("prompts/STATE.template.md", "docs/STATE.md")
        self.copy_template("prompts/EXPERIMENTS.template.md", "docs/EXPERIMENTS.md")
        self.append_once("dashboard/app.py", MARK_APP, APP_SNIPPET)
        self.append_once(".gitignore", "# qrl-v0.3", "# qrl-v0.3 generated files (rebuilt by the dispatcher)\n"
                         "docs/INDEX.md\ndocs/index.json\n")
        self.home_file("deploy/codex-qrl-lab.rules", os.path.join(HOME, ".codex", "rules", "qrl-lab.rules"))
        self.env_file()
        for unit in ("qrl-dispatcher.service", "qrl-dashboard.service"):
            self.home_file(f"deploy/{unit}", os.path.join(HOME, ".config", "systemd", "user", unit),
                           {"{ROOT}": self.root})
        if self.apply:
            os.makedirs(os.path.join(self.root, "docs", "journal"), exist_ok=True)
            sys.path.insert(0, os.path.join(self.root, "tools"))
            import build_md_index
            n = build_md_index.build(self.root)
            self.changes.append(f"docs/INDEX.md: {n} αρχεία .md")
        return self.changes


def main(argv=None):
    ap = argparse.ArgumentParser(description="Install QRL-Lab v0.3")
    ap.add_argument("--apply", action="store_true")
    a = ap.parse_args(argv)
    inst = Installer(ROOT, a.apply)
    changes = inst.run()
    head = "Έγιναν" if a.apply else "Θα γίνουν (τίποτα δεν γράφτηκε· τρέξε με --apply)"
    print(f"{head}:" if changes else "Τίποτα να αλλάξει: όλα είναι ήδη εγκατεστημένα.")
    for c in changes:
        print("  -", c)
    if a.apply and changes:
        print(f"Αντίγραφα ασφαλείας: {os.path.relpath(inst.backup, ROOT)}/")
    if a.apply:
        print("\nΕπόμενα βήματα (εσύ):\n"
              "  tmux kill-session -t lab                       # σταματά τον παλιό μόνιμο συντονιστή\n"
              "  sudo loginctl enable-linger $USER              # οι υπηρεσίες τρέχουν και χωρίς σύνδεση SSH\n"
              "  systemctl --user daemon-reload\n"
              "  systemctl --user enable --now qrl-dashboard qrl-dispatcher\n"
              "  python3 tools/dispatcher.py status")


if __name__ == "__main__":
    main()
